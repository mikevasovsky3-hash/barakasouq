function isMasterFreeActive() {
  if (!MASTER_FREE_CONFIG || !MASTER_FREE_CONFIG.enabled) return false;
  const type = MASTER_FREE_CONFIG.conditionType || 'always';
  const target = Number(MASTER_FREE_CONFIG.targetValue) || 0;

  if (type === 'always') return true;

  if (type === 'shops_count') {
    const shopsCount = (typeof users !== 'undefined' && Array.isArray(users)) ? users.filter(u => u.shop).length : 0;
    return shopsCount < target;
  }

  if (type === 'ads_count') {
    const adsCount = (typeof ads !== 'undefined' && Array.isArray(ads)) ? ads.filter(a => a.status === 'ACTIVE').length : 0;
    return adsCount < target;
  }

  if (type === 'users_count') {
    const usersCount = (typeof users !== 'undefined' && Array.isArray(users)) ? users.length : 0;
    return usersCount < target;
  }

  if (type === 'days_timer') {
    const start = Number(MASTER_FREE_CONFIG.startDate) || Date.now();
    const durationMs = target * 86400000;
    return Date.now() < (start + durationMs);
  }

  if (type === 'until_date') {
    const untilTs = new Date(MASTER_FREE_CONFIG.targetValue).getTime();
    return !isNaN(untilTs) && Date.now() < untilTs;
  }

  return true;
}

